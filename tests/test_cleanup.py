    def test_examples(self):
        examples = [
            ("어 오늘 출발해요", "오늘 출발해요."),
            ("음, 내일 만나요", "내일 만나요."),
            ("아, 자료를 주세요", "자료를 주세요."),
            ("그럼 어 음 다시 해요", "그럼 다시 해요."),
            ("어, 음, 아", ""),
            ("음악과 아이디어를 모아요", "음악과 아이디어를 모아요."),
            ("오늘 오늘 오늘 출발합니다", "오늘 출발합니다."),
            ("회의 자료 회의 자료 준비해요", "회의 자료 준비해요."),
            ("준비, 준비 시작", "준비 시작."),
            ("월요일 아니 그게 아니라 화요일에 가요", "화요일에 가요."),
            ("회의는 월요일 아니, 그게 아니라 수요일이에요", "회의는 수요일이에요."),
            ("자료를 받았어요. 부산행 아니 그게 아니라 대전행 표 주세요",
             "자료를 받았어요. 대전행 표 주세요."),
            ("내일 만나요 다시 말할게요 다음 주에 만나요", "다음 주에 만나요."),
            ("시간을 정해요. 회의는 월요일. 아니, 그게 아니라 수요일이에요.",
             "시간을 정해요. 회의는 수요일이에요."),
            ("내일 세 시, 아니 네 시에 만나요", "내일 네 시에 만나요."),
            ("내일 오후 세 시, 아니 네 시에 만나요", "내일 오후 네 시에 만나요."),
            ("이번 주 월요일 아니 그게 아니라 화요일에 봐요", "이번 주 화요일에 봐요."),
            ("아니요 그게 맞아요", "아니요 그게 맞아요."),
            ("API API 응답을   볼까요 ?", "API 응답을 볼까요?"),
            ("오후 3.5시간 동안 할수있어요", "오후 3.5시간 동안 할 수 있어요."),
            ("같이 갈까요", "같이 갈까요?"),
            ("파일 sample.wav 열어요", "파일 sample.wav 열어요."),
            ("음... 오늘 만나요", "오늘 만나요."),
        ]
        for raw, expected in examples:
            with self.subTest(raw=raw):
                self.assertEqual(clean(raw), expected)
                self.assertEqual(clean(expected), expected)
